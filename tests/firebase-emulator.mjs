import assert from 'node:assert/strict';
import { initializeApp as initializeAdmin } from 'firebase-admin/app';
import { getAuth as adminAuth } from 'firebase-admin/auth';
import { initializeApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, signInWithEmailAndPassword, signOut, confirmPasswordReset } from 'firebase/auth';
import { administratorEmail, isAdministrator, hasRecentSignIn, sessionDurationMs } from '../lib/auth-policy.ts';

// This script refuses to run against a real Firebase project or remote host.
const projectId = 'demo-sklcf-auth';
const host = process.env.FIREBASE_AUTH_EMULATOR_HOST;
assert.ok(host && /^(127\.0\.0\.1|localhost):\d+$/.test(host), 'Run only through the local Firebase Auth emulator.');
const admin = adminAuth(initializeAdmin({ projectId }));
const auth = getAuth(initializeApp({ projectId, apiKey: 'emulator-only-key', authDomain: 'localhost' }));
connectAuthEmulator(auth, `http://${host}`, { disableWarnings: true });
const uid = 'test-owner-uid';
const initialPassword = 'Emulator-test-only-2026';
const changedPassword = 'Emulator-changed-only-2026';
const resetPassword = 'Emulator-reset-only-2026';
await admin.createUser({ uid, email: administratorEmail, password: initialPassword });
await assert.rejects(signInWithEmailAndPassword(auth, administratorEmail, 'wrong-password'));
const credential = await signInWithEmailAndPassword(auth, administratorEmail, initialPassword);
const idToken = await credential.user.getIdToken();
const claims = await admin.verifyIdToken(idToken, true);
assert.equal(isAdministrator(claims, uid), true);
assert.equal(isAdministrator(claims, 'other-uid'), false);
assert.equal(hasRecentSignIn(claims.auth_time), true);
const cookie = await admin.createSessionCookie(idToken, { expiresIn: sessionDurationMs });
assert.equal(isAdministrator(await admin.verifySessionCookie(cookie, true), uid), true);
await signOut(auth);
await new Promise(resolve => setTimeout(resolve, 1100));
await admin.updateUser(uid, { password: changedPassword });
await admin.revokeRefreshTokens(uid);
await assert.rejects(admin.verifySessionCookie(cookie, true));
await assert.rejects(signInWithEmailAndPassword(auth, administratorEmail, initialPassword));
await signInWithEmailAndPassword(auth, administratorEmail, changedPassword);
await signOut(auth);
const resetLink = await admin.generatePasswordResetLink(administratorEmail);
const code = new URL(resetLink).searchParams.get('oobCode');
assert.ok(code);
await confirmPasswordReset(auth, code, resetPassword);
await assert.rejects(signInWithEmailAndPassword(auth, administratorEmail, changedPassword));
await signInWithEmailAndPassword(auth, administratorEmail, resetPassword);
await signOut(auth);
console.log('PASS: Firebase sign-in, owner policy, session issuance, password change, session revocation and password reset (local emulator only).');
